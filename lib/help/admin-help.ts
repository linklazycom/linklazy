/**
 * The key of the entry that fits a path: the most specific one. A key may contain "[id]" for one path segment (e.g. /admin/disputes/[id]);
 * "/admin" matches only the Overview itself, every other key also matches the pages below it. Pure, so the button and the tests share it.
 */
export function pickHelpKey(path: string, keys: string[]): string | null {
  let best: string | null = null;
  let bestScore = -1;
  for (const key of keys) {
    let hit: boolean;
    if (key === "/admin") hit = path === "/admin";
    else {
      const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const re = new RegExp(`^${key.split("[id]").map(escape).join("[^/]+")}(/.*)?$`);
      hit = re.test(path);
    }
    if (!hit) continue;
    const score = key.length;
    if (score > bestScore) {
      best = key;
      bestScore = score;
    }
  }
  return best;
}

/** The entry for a page, or null when none is written yet. */
export function helpForPath(path: string): { key: string; entry: HelpEntry } | null {
  const key = pickHelpKey(path, Object.keys(ADMIN_HELP));
  return key ? { key, entry: ADMIN_HELP[key] } : null;
}
