/** The entry for a page: the longest key that is a prefix of the path, or null. */
export function helpForPath(path: string): { key: string; entry: HelpEntry } | null {
  let best: string | null = null;
  for (const key of Object.keys(ADMIN_HELP)) {
    if ((path === key || path.startsWith(`${key}/`)) && (best === null || key.length > best.length)) best = key;
  }
  return best ? { key: best, entry: ADMIN_HELP[best] } : null;
}
